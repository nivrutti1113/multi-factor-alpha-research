@pytest.fixture
def sample_price_history():
    """Generates synthetic price history DataFrame (500 days x 10 tickers)."""
    np.random.seed(42)
    dates = pd.date_range("2020-01-01", periods=500, freq="B")
    tickers = [f"STK_{i}" for i in range(10)]
    prices = pd.DataFrame(
        100.0 + np.random.randn(500, 10).cumsum(axis=0), index=dates, columns=tickers
    )
    return prices


def test_signal_no_future_dependence(sample_price_history):
    """Asserts that mutating future price data (t > t_cutoff) leaves historical signal values
    for all t <= t_cutoff completely unchanged.
    """
    prices_orig = sample_price_history.copy()
    cutoff_idx = 350
    t_cutoff = prices_orig.index[cutoff_idx]

    sig_orig = compute_momentum_12_1(prices_orig, lookback_days=252, skip_days=21)

    prices_perturbed = prices_orig.copy()
    prices_perturbed.iloc[cutoff_idx + 1 :] = prices_perturbed.iloc[cutoff_idx + 1 :] * 10.0 + 500.0

    sig_perturbed = compute_momentum_12_1(prices_perturbed, lookback_days=252, skip_days=21)

    sig_orig_history = sig_orig.loc[:t_cutoff].dropna()
    sig_perturbed_history = sig_perturbed.loc[:t_cutoff].dropna()

    pd.testing.assert_frame_equal(sig_orig_history, sig_perturbed_history)
    print("PASS: Signal at time t has zero dependence on future data (t > t_cutoff).")


def test_signal_reversal_skip(sample_price_history):
    """Asserts that Jegadeesh-Titman 12-1 momentum skips the recent month (t-21 to t).
    Mutating prices in window [t-20 to t] MUST NOT change Signal(t).
    """
    prices_orig = sample_price_history.copy()
    target_idx = 350
    t_target = prices_orig.index[target_idx]

    sig_orig = compute_momentum_12_1(prices_orig, lookback_days=252, skip_days=21)
    orig_val = sig_orig.loc[t_target]

    prices_mutated = prices_orig.copy()
    prices_mutated.iloc[target_idx - 20 : target_idx + 1] = (
        prices_mutated.iloc[target_idx - 20 : target_idx + 1] * 5.0
    )

    sig_mutated = compute_momentum_12_1(prices_mutated, lookback_days=252, skip_days=21)
    mutated_val = sig_mutated.loc[t_target]

    pd.testing.assert_series_equal(orig_val, mutated_val)
    print("PASS: Recent 1-month window (t-21 to t) is successfully skipped.")


def test_quantile_weights_sum_to_zero(sample_price_history):
    """Asserts that portfolio weights generated by compute_quantile_weights are strictly
    dollar-neutral (Long sum = +1.0, Short sum = -1.0, Total sum = 0.0).
    """
    sig = compute_momentum_12_1(sample_price_history, lookback_days=252, skip_days=21)
    ranks, weights = compute_quantile_weights(sig, num_quantiles=5)

    valid_weights = weights.dropna(how="all").iloc[260:]

    for date in valid_weights.index:
        row_w = valid_weights.loc[date]
        long_sum = row_w[row_w > 0].sum()
        short_sum = row_w[row_w < 0].sum()
        total_sum = row_w.sum()

        if abs(long_sum) > 0:
            pytest.approx(long_sum, 1.0)
            pytest.approx(short_sum, -1.0)
            pytest.approx(total_sum, 0.0, abs=1e-6)

    print("PASS: Portfolio weights are strictly dollar-neutral.")


def test_point_in_time_universe_construction():
    """Asserts that build_point_in_time_mask correctly marks historical removed tickers
    as True prior to their delisting date and False on/after delisting date.
    """
    dates = pd.date_range("2015-01-01", "2024-12-31", freq="B")
    tickers = ["AAPL", "TWTR", "SIVB"]
    current_universe = ["AAPL"]
    csv_path = "data/sp500_historical_changes.csv"

    if os.path.exists(csv_path):
        pit_mask = build_point_in_time_mask(dates, tickers, current_universe, csv_path)
        assert pit_mask.loc["2022-10-27", "TWTR"]
        assert not pit_mask.loc["2022-10-28", "TWTR"]
        assert pit_mask.loc["2023-03-14", "SIVB"]
        assert not pit_mask.loc["2023-03-15", "SIVB"]

        print("PASS: Point-in-time universe construction rules verified.")


def test_value_factor_signal_construction(sample_price_history):
    """Asserts that compute_value_signal_ep correctly constructs Earnings Yield signal."""
    ey_df = pd.DataFrame(
        0.05, index=sample_price_history.index, columns=sample_price_history.columns
    )
    ey_df.iloc[100:, 0] = 0.10  # STK_0 becomes high earnings yield / cheap

    val_signal = compute_value_signal_ep(sample_price_history, ey_df)
    ranks, weights = compute_quantile_weights(val_signal, num_quantiles=5)

    assert val_signal.shape == sample_price_history.shape
    assert weights.shape == sample_price_history.shape
    print("PASS: Earnings Yield Value factor signal construction verified.")


